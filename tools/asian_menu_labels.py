def labels(language,keys):
    column=1 if language=='ja' else 2
    translations={row.split('|')[0].strip():row.split('|')[column]for row in LABELS.splitlines()if row}
    # Fullwidth colon/exclamation share the same retail glyph as ASCII.
    def normalize(s):
        s=s.replace('：',':').replace('！','!').replace('？','?')
        if language=='ko':s=s.translate(str.maketrans('１２','12'))
        return s
    return {key:{'value':normalize(translations[key.strip()])}for key in keys if key.strip()in translations}
