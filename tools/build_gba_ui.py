"""Compile authored GBA UI; ROM-derived Strings pairs take precedence at runtime."""
import json,re
from pathlib import Path
from build_european_gb import lua
ROOT=Path(__file__).resolve().parents[1]
LANGUAGES=('de','es','fr','it')
TOKEN=re.compile(r'\{[^{}]*\}|%(?:\d+\$)?[-+ #0]*\d*(?:\.\d+)?[a-zA-Z%]')
def unescape(s):return s.replace('\\n','\n').replace('\\f','\f')
def catalog():
 shared=json.loads((ROOT/'translations/european/gb-ui.json').read_text())
 result={lang:{} for lang in LANGUAGES}
 for name in ('ui-extra.tsv','ui-common-de.tsv'):
  for line in (ROOT/'translations/gba'/name).read_text().splitlines():
   if not line or line.startswith('#'):continue
   cells=list(map(unescape,line.split('|')));source=cells[0]
   if len(cells)==2:
    if source in result['de']:continue
    cells+=shared[source]
   assert len(cells)==5,(name,line)
   for lang,text in zip(LANGUAGES,cells[1:]):
    assert source not in result[lang],('Duplicate',source)
    assert text.strip(),(source,lang)
    assert TOKEN.findall(source)==TOKEN.findall(text),(source,lang,text)
    assert source.count('\f')==text.count('\f'),(source,lang,'paragraphs')
    result[lang][source]=text
 # Slot fallback icon labels identify pictures; localized species initials
 # match the native names. Native reel art is unaffected.
 icons={'de':['7','R','PI','EN','KI','MA','MU'],'es':['7','R','PI','PS','CE','MA','SH'],
        'fr':['7','R','PI','PS','CE','MA','KO'],'it':['7','R','PI','PS','CI','MA','SH']}
 for lang,values in icons.items():
  result[lang].update(zip(('7','R','PI','PS','CH','MA','SH'),values))
  for key in ('A','B','L','SELECT','START'):result[lang][key]=key
 return result
if __name__=='__main__':
 data=catalog()
 (ROOT/'mod/gba/ui.lua').write_text('-- Generated by tools/build_gba_ui.py; authored engine UI only.\nreturn '+lua(data)+'\n')
 print('GBA_UI_BUILD_OK',len(data['de']),'keys x',len(data),'languages')
